async(page)=>{
  const checks=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
  const check=(name,pass,evidence)=>{checks.push({name,pass,evidence});if(!pass)throw Error(name+': '+JSON.stringify(evidence));};
  await page.setViewportSize({width:1920,height:1080});
  await page.goto('http://127.0.0.1:5173/?qa=1');await page.waitForFunction(()=>window.__M3);
  const state=()=>page.evaluate(()=>window.__M3.snapshot());
  const drag=async(a,b)=>{await page.mouse.move(...a);await page.mouse.down();await page.mouse.move(...b,{steps:8});await page.mouse.up();await page.waitForTimeout(80);return state();};
  await page.getByRole('button',{name:'Explore by dragging',exact:true}).click();
  check('explicit drag entry clears opening panel',await page.locator('.intro').count()===0);
  check('drag entry requires no mouse lock',!(await state()).locked);
  const initial=await state();const right=await drag([960,600],[1180,600]);
  check('dragging right turns view right',right.yaw<initial.yaw-.35,right.yaw);
  const left=await drag([1180,600],[960,600]);check('dragging left turns view left',left.yaw>right.yaw+.35,left.yaw);
  const vertical=await drag([960,600],[960,760]);check('vertical drag looks down',vertical.pitch<left.pitch-.25,vertical.pitch);
  check('looking does not move the walker',Math.hypot(vertical.position[0]-initial.position[0],vertical.position[2]-initial.position[2])<.01);
  await page.mouse.move(1250,600);check('released mouse does not keep turning',Math.abs((await state()).yaw-vertical.yaw)<.001);
  await page.getByRole('button',{name:'Field notes'}).click();
  const beforeOverlay=await state();await drag([1000,550],[1800,550]);
  check('drag continues across an overlay using pointer capture',(await state()).yaw<beforeOverlay.yaw-1.4);
  await page.getByRole('button',{name:'Close field notes'}).click();
  await page.evaluate(()=>{window.__nativeLock=HTMLCanvasElement.prototype.requestPointerLock;HTMLCanvasElement.prototype.requestPointerLock=()=>Promise.reject(new Error('capture denied for test'));});
  await page.getByRole('button',{name:'Enable mouse look'}).click();await page.waitForTimeout(100);
  check('capture rejection leaves view unobstructed',await page.locator('.intro').count()===0&&!(await state()).locked);
  const failed=await state();await drag([960,600],[1160,600]);check('horizontal drag works after capture rejection',(await state()).yaw<failed.yaw-.35);
  await page.evaluate(()=>{HTMLCanvasElement.prototype.requestPointerLock=window.__nativeLock;delete window.__nativeLock;});
  await page.getByRole('button',{name:'Enable mouse look'}).click();await page.waitForTimeout(150);
  check('native mouse capture can resume',(await state()).locked);
  const captured=await state();await page.mouse.move(1330,600,{steps:8});await page.waitForTimeout(80);
  check('captured mouse movement rotates horizontal view',Math.abs((await state()).yaw-captured.yaw)>.15,{before:captured.yaw,after:(await state()).yaw});
  await page.evaluate(()=>document.exitPointerLock());await page.waitForTimeout(100);
  const escaped=await state();await drag([960,600],[760,600]);check('drag look works immediately after Escape',(await state()).yaw>escaped.yaw+.35);
  await page.evaluate(()=>window.__M3.reset());await page.keyboard.down('KeyD');await page.waitForTimeout(250);await page.keyboard.up('KeyD');
  check('sideways walking still works in drag mode',(await state()).position[0]>.3);
  await page.evaluate(()=>window.__M3.aim([0,1.72,1.3],[0,1.2,-.305]));await page.waitForTimeout(100);await page.keyboard.press('KeyE');await page.waitForTimeout(950);
  check('E operates aimed front door in drag mode',(await state()).door>.99);
  await page.goto('http://127.0.0.1:5173/?qa=1');await page.waitForFunction(()=>window.__M3);
  await page.evaluate(()=>{HTMLCanvasElement.prototype.requestPointerLock=()=>Promise.reject(new Error('capture denied at entry'));});
  await page.getByRole('button',{name:'Explore the store',exact:false}).click();await page.waitForTimeout(100);
  check('first entry clears the opening panel even if capture is denied',await page.locator('.intro').count()===0);
  const fallback=await state();await drag([960,600],[1180,600]);
  check('first-entry fallback permits horizontal looking',(await state()).yaw<fallback.yaw-.35);
  check('no runtime errors',errors.length===0,errors);
  return {checks,errors,userAgent:await page.evaluate(()=>navigator.userAgent)};
}
